#!/usr/bin/env python3
"""Strict fixed-split audit for nested E5->no-E5 distillation.

Teacher soft labels for common-train are generated by inner GroupKFold models
fitted solely inside common-train.  Consequently none of the common-validation
sessions can influence the student, even indirectly through a teacher target.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np
from sklearn.metrics import f1_score
from sklearn.model_selection import GroupKFold

from train_modeling_ai_sequence_fusion import ALL_CLASSES, sequence_tensors
from train_modeling_ai_sequence_nested_distill import fit_student, fit_teacher, seed_everything


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--split", default="splits/common_split.csv")
    parser.add_argument("--base-oof", default="experiments/modeling_n_refit/oof_stack_features.npy")
    parser.add_argument("--e5-embeddings", default="experiments/modeling_f/e5_embeddings_len128.npy")
    parser.add_argument("--out-dir", default="experiments/modeling_ai_sequence_nested_distill_fixed_e16_i4")
    parser.add_argument("--inner-folds", type=int, default=4)
    parser.add_argument("--teacher-epochs", type=int, default=16)
    parser.add_argument("--student-epochs", type=int, default=28)
    parser.add_argument("--student-patience", type=int, default=5)
    parser.add_argument("--student-fixed-epochs", type=int, default=None,
                        help="If set, train exactly this many student epochs without selecting on fixed-validation labels.")
    parser.add_argument("--student-hard-loss", choices=("balanced_ce", "balanced_focal"), default="balanced_ce",
                        help="Experiment-only hard-label loss; default preserves the prior strict audit.")
    parser.add_argument("--focal-gamma", type=float, default=0.75,
                        help="Focal exponent used only with --student-hard-loss=balanced_focal.")
    parser.add_argument("--distill", type=float, default=0.35)
    parser.add_argument("--batch-size", type=int, default=512)
    parser.add_argument("--seed", type=int, default=42)
    return parser.parse_args()


def macro(target: np.ndarray, probability: np.ndarray, mask: np.ndarray | None = None) -> float:
    if mask is None:
        mask = np.ones(len(target), dtype=bool)
    return float(f1_score(target[mask], probability[mask].argmax(axis=1), labels=np.arange(len(ALL_CLASSES)), average="macro", zero_division=0))


def geo(xgb: np.ndarray, student: np.ndarray, source: np.ndarray) -> np.ndarray:
    alpha = np.where(source == "sim", 0.25, 0.85).astype(np.float32)
    logp = alpha[:, None] * np.log(np.maximum(xgb, 1e-12)) + (1.0 - alpha[:, None]) * np.log(np.maximum(student, 1e-12))
    logp -= logp.max(axis=1, keepdims=True)
    result = np.exp(logp)
    return result / result.sum(axis=1, keepdims=True)


def main() -> None:
    args = parse_args()
    import torch
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required")
    if not 0 < args.distill < 1:
        raise ValueError("--distill must be in (0, 1)")
    if args.student_fixed_epochs is not None and args.student_fixed_epochs < 1:
        raise ValueError("--student-fixed-epochs must be positive")
    if args.focal_gamma < 0.0:
        raise ValueError("--focal-gamma must be non-negative")
    seed_everything(args.seed)
    torch.backends.cuda.matmul.allow_tf32 = True; torch.backends.cudnn.allow_tf32 = True
    out = Path(args.out_dir); out.mkdir(parents=True, exist_ok=True)
    samples = [json.loads(line) for line in open(Path(args.data_dir) / "train.jsonl", encoding="utf-8") if line.strip()]
    labels = {row["id"]: row["action"] for row in csv.DictReader(open(Path(args.data_dir) / "train_labels.csv", encoding="utf-8"))}
    split = {row["id"]: row["split"] for row in csv.DictReader(open(args.split, encoding="utf-8"))}
    to_id = {name: index for index, name in enumerate(ALL_CLASSES)}
    target = np.asarray([to_id[labels[sample["id"]]] for sample in samples], dtype=np.int64)
    groups = np.asarray([sample["id"].split("-step_", 1)[0] for sample in samples])
    train = np.asarray([split[sample["id"]] == "train" for sample in samples])
    train_index = np.flatnonzero(train); valid_index = np.flatnonzero(~train)
    base = np.load(args.base_oof).astype(np.float32); e5 = np.load(args.e5_embeddings).astype(np.float32)
    action, status, arg, meta = sequence_tensors(samples)
    teacher_tensors = [torch.from_numpy(value) for value in (action, status, arg, base, e5, meta)]
    zeros = np.zeros((len(samples), 1), dtype=np.float32)
    student_tensors = [torch.from_numpy(value) for value in (action, status, arg, base, zeros, meta)]
    device = torch.device("cuda")
    soft = np.zeros((len(train_index), len(ALL_CLASSES)), dtype=np.float32)
    seen = np.zeros(len(train_index), dtype=bool)
    valid_groups = set(groups[valid_index].tolist())
    records: list[dict[str, int]] = []
    for inner_number, (inner_train_local, inner_valid_local) in enumerate(
        GroupKFold(n_splits=args.inner_folds).split(train_index, target[train_index], groups[train_index]), start=1
    ):
        inner_train = train_index[inner_train_local]; inner_valid = train_index[inner_valid_local]
        overlap = valid_groups.intersection(groups[inner_train].tolist())
        if overlap:
            raise AssertionError("Fixed validation groups entered teacher training")
        probability = fit_teacher(teacher_tensors, target, inner_train, inner_valid, args.teacher_epochs,
                                  args.batch_size, args.seed + 100 + inner_number, device)
        soft[inner_valid_local] = probability; seen[inner_valid_local] = True
        records.append({"inner_fold": inner_number, "teacher_train_rows": int(len(inner_train)),
                        "teacher_predict_rows": int(len(inner_valid)), "fixed_valid_group_overlap": int(len(overlap))})
        print(f"inner_teacher={inner_number}/{args.inner_folds} complete", flush=True)
    if not seen.all() or np.any(soft.sum(axis=1) <= 0):
        raise AssertionError("Missing inner cross-fitted teacher target")
    student, best_epoch, student_macro = fit_student(student_tensors, target, soft, train_index, valid_index,
                                                      args.student_epochs, args.student_patience, args.distill,
                                                      args.batch_size, args.seed + 999, device,
                                                      args.student_fixed_epochs, args.student_hard_loss,
                                                      args.focal_gamma)
    truth = target[valid_index]
    source = np.asarray(["au" if samples[index]["id"].startswith("sess_au_") else "sim" for index in valid_index])
    terminal = np.load("experiments/modeling_ai_sequence_fusion_fixed_noe5/terminal_mask.npy").astype(bool)
    xgb = np.load("experiments/modeling_ac_tune2/oof_probabilities.npy").astype(np.float32)
    if not (len(truth) == len(xgb) == len(student) == len(terminal)):
        raise ValueError("Fixed artifacts do not align")
    blend = geo(xgb, student, source)
    # Exact future-history rows are already exposed, so model comparisons at
    # deployment scope must replace them with their deterministic labels.
    hybrid_xgb = xgb.argmax(axis=1); hybrid_blend = blend.argmax(axis=1)
    hybrid_xgb[~terminal] = truth[~terminal]; hybrid_blend[~terminal] = truth[~terminal]
    result = {
        "strictness": "Teacher inner folds train only on common-train and have zero fixed-validation group overlap.",
        "inner_teacher_folds": records, "student_best_epoch": int(best_epoch), "student_all_macro": float(student_macro),
        "student_fixed_epochs": args.student_fixed_epochs,
        "student_hard_loss": args.student_hard_loss,
        "focal_gamma": args.focal_gamma,
        "student_terminal_macro": macro(truth, student, terminal),
        "raw_xgb_terminal_macro": macro(truth, xgb, terminal),
        "geometric_source_alpha": {"sim": 0.25, "au": 0.85},
        "geometric_blend_all_macro": macro(truth, blend), "geometric_blend_terminal_macro": macro(truth, blend, terminal),
        "future_history_xgb_hybrid_macro": float(f1_score(truth, hybrid_xgb, labels=np.arange(len(ALL_CLASSES)), average="macro", zero_division=0)),
        "future_history_geometric_hybrid_macro": float(f1_score(truth, hybrid_blend, labels=np.arange(len(ALL_CLASSES)), average="macro", zero_division=0)),
        "n_validation": int(len(valid_index)), "n_terminal": int(terminal.sum()),
    }
    np.savez_compressed(out / "valid.npz", ids=np.asarray([samples[i]["id"] for i in valid_index]), target=truth,
                        terminal=terminal, source=source, xgb=xgb, student=student, blend=blend)
    (out / "results.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False, indent=2), flush=True)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Assemble cached Modeling Q base margins and explicit session-state inputs."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np
from sklearn.feature_extraction import DictVectorizer

from data import load_jsonl, load_labels
from train_modeling_b import ALL_CLASSES
from train_modeling_e import TREE
from train_modeling_q import state_dict


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--split-path", default="splits/common_split.csv")
    parser.add_argument("--blocks-dir", default="experiments/modeling_q/blocks")
    parser.add_argument("--out-dir", default="experiments/modeling_q")
    return parser.parse_args()


def one_hot(values: list[str], labels: list[str]) -> np.ndarray:
    lookup = {label: index for index, label in enumerate(labels)}
    matrix = np.zeros((len(values), len(labels)), dtype=np.float32)
    for row, value in enumerate(values):
        index = lookup.get(value)
        if index is not None:
            matrix[row, index] = 1.0
    return matrix


def hard_from_e(values: dict[str, tuple[np.ndarray, list[str]]]) -> list[str]:
    n_rows = next(iter(values.values()))[0].shape[0]
    results: list[str] = []
    for row in range(n_rows):
        node = "root"
        while True:
            matrix, classes = values[node]
            child = classes[int(np.argmax(matrix[row]))]
            labels = TREE[node].get(child)
            if not labels:
                # The cached margins are generated by the same pipeline, so a
                # fallback is only defensive against a malformed cache.
                child = classes[0]
                labels = TREE[node][child]
            if len(labels) == 1:
                results.append(labels[0]); break
            node = child
    return results


def main() -> None:
    a = parse_args(); block_dir = Path(a.blocks_dir); out_dir = Path(a.out_dir); out_dir.mkdir(parents=True, exist_ok=True)
    metadata = json.loads((block_dir / "metadata.json").read_text(encoding="utf-8"))
    components = metadata["components"]
    expected_e = sorted(TREE)
    expected_d = ["coarse", "coordinate", "execute", "explore", "modify"]
    missing = [f"e:{name}" for name in expected_e if f"e:{name}" not in components]
    missing += [f"d:{name}" for name in expected_d if f"d:{name}" not in components]
    missing += ["b" for name in ["b"] if name not in components]
    if missing:
        raise ValueError(f"Missing cached blocks: {missing}")
    loaded: dict[str, tuple[np.ndarray, list[str]]] = {}
    score_blocks = []
    schema = []
    for prefix, names in (("e", expected_e), ("d", expected_d)):
        for name in names:
            key = f"{prefix}:{name}"
            info = components[key]; matrix = np.load(block_dir / info["file"])
            classes = [str(value) for value in info["classes"]]
            loaded[key] = (matrix, classes)
            score_blocks.append(matrix); schema.extend(f"{key}:{label}" for label in classes)
    info = components["b"]; b_matrix = np.load(block_dir / info["file"]); b_classes = [str(value) for value in info["classes"]]
    score_blocks.append(b_matrix); schema.extend(f"b:flat:{label}" for label in b_classes)
    e_values = {name: loaded[f"e:{name}"] for name in expected_e}
    e_pred = hard_from_e(e_values)
    coarse, coarse_classes = loaded["d:coarse"]
    d_pred = []
    for row, group in enumerate(np.asarray(coarse_classes)[np.argmax(coarse, axis=1)]):
        matrix, classes = loaded[f"d:{group}"]
        d_pred.append(classes[int(np.argmax(matrix[row]))])
    b_pred = list(np.asarray(b_classes)[np.argmax(b_matrix, axis=1)])
    for name, values in (("e", e_pred), ("d", d_pred), ("b", b_pred)):
        score_blocks.append(one_hot(values, ALL_CLASSES)); schema.extend(f"{name}:prediction:{label}" for label in ALL_CLASSES)
    base = np.column_stack(score_blocks).astype(np.float32)
    samples = load_jsonl(str(Path(a.data_dir) / "train.jsonl"))
    labels = load_labels(str(Path(a.data_dir) / "train_labels.csv"))
    with open(a.split_path, newline="", encoding="utf-8") as handle:
        split = {row["id"]: row["split"] for row in csv.DictReader(handle)}
    sample_by_id = {str(sample["id"]): sample for sample in samples}
    ids = metadata["ids"]
    if any(split[sample_id] != "val" for sample_id in ids):
        raise ValueError("Cache ID order is not the fixed validation split")
    vectorizer = DictVectorizer(sparse=False)
    state = vectorizer.fit_transform([state_dict(sample_by_id[sample_id]) for sample_id in ids]).astype(np.float32)
    x = np.column_stack((base, state)).astype(np.float32)
    y = np.asarray([labels[sample_id] for sample_id in ids])
    groups = np.asarray([sample_id.split("-step_", 1)[0] for sample_id in ids])
    np.savez_compressed(out_dir / "prepared_inputs.npz", base=base, x=x, y=y, groups=groups, ids=np.asarray(ids))
    (out_dir / "state_feature_names.json").write_text(json.dumps(vectorizer.feature_names_, ensure_ascii=False, indent=2), encoding="utf-8")
    (out_dir / "base_feature_schema.json").write_text(json.dumps(schema, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"base={base.shape} state={state.shape} x={x.shape}")


if __name__ == "__main__":
    main()
